#!/usr/bin/env python3
"""Emit an FTN5 program that replays validation/cases.txt.

The generated program uses REAL add, subtract, multiply, and divide
so the Cyber floating-point unit performs the operations. Each result
word is stored by EQUIVALENCE and printed as 20 octal digits with
SHIFT and .AND., which NOS 2 FTN5 sources in DtCyber already use.
Signed zero is `.NOT. 0` (60 one-bits), not a real literal.
"""

import argparse
import sys


def parse_cases(path):
    cases = []
    with open(path, "r", encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 3:
                raise SystemExit(f"FAIL: {path}:{lineno}: short case")
            ident, op = parts[0], parts[1]
            if len(ident) > 7 or not ident[0].isalpha():
                raise SystemExit(f"FAIL: {path}:{lineno}: bad id {ident}")
            cases.append((ident, op, parts[2:], lineno))
    return cases


def lit_fortran(token):
    if token in ("+0", "0", "+0.0"):
        return "zero"
    if token in ("-0", "-0.0"):
        return "mzero"
    if token.startswith("+"):
        token = token[1:]
    if "." not in token and "e" not in token.lower():
        token = token + ".0"
    return token


def emit(cases):
    index = {ident: i + 1 for i, (ident, _op, _args, _ln) in enumerate(cases)}
    n = len(cases)
    if n > 80:
        raise SystemExit("FAIL: more than 80 cases")
    lines = []
    a = lines.append
    a("      PROGRAM CDCFPC")
    a("C")
    a("C  Replay cdc_fp/validation/cases.txt on NOS FTN5.")
    a("C  Generated by validation/scripts/emit_ftn.py.")
    a("C  OPT=0 so the DO loops stay multiplies.")
    a("C")
    a("      INTEGER W(80), IA, IB, IC, K")
    a("      REAL RA, RB, RC")
    a("      EQUIVALENCE (RA, IA), (RB, IB), (RC, IC)")
    a("C")
    for ncase, (ident, op, args, lineno) in enumerate(cases, 1):
        lab = 100 + ncase
        if op == "lit":
            if len(args) != 1:
                raise SystemExit(f"FAIL: line {lineno}: lit arity")
            kind = lit_fortran(args[0])
            if kind == "zero":
                a(f"      RA = 0.0")
                a(f"      W({ncase}) = IA")
            elif kind == "mzero":
                a(f"      IA = .NOT. 0")
                a(f"      W({ncase}) = IA")
            else:
                a(f"      RA = {kind}")
                a(f"      W({ncase}) = IA")
        elif op in ("add", "sub", "mul", "div"):
            if len(args) != 2 or args[0] not in index or args[1] not in index:
                raise SystemExit(f"FAIL: line {lineno}: bad {op}")
            if index[args[0]] >= ncase or index[args[1]] >= ncase:
                raise SystemExit(f"FAIL: line {lineno}: forward ref")
            sym = {"add": "+", "sub": "-", "mul": "*", "div": "/"}[op]
            a(f"      IA = W({index[args[0]]})")
            a(f"      IB = W({index[args[1]]})")
            a(f"      RC = RA {sym} RB")
            a(f"      W({ncase}) = IC")
        elif op == "muln":
            if len(args) != 3 or args[0] not in index or args[1] not in index:
                raise SystemExit(f"FAIL: line {lineno}: bad muln")
            count = int(args[2])
            if count < 1 or count > 64:
                raise SystemExit(f"FAIL: line {lineno}: muln count")
            a(f"      IA = W({index[args[0]]})")
            a(f"      IB = W({index[args[1]]})")
            a(f"      DO {lab} K = 1, {count}")
            a("        RA = RA * RB")
            a(f"{lab:5d} CONTINUE")
            a(f"      W({ncase}) = IA")
        else:
            raise SystemExit(f"FAIL: line {lineno}: unknown op {op}")
        a(f"      CALL PUTO('{ident}', W({ncase}))")
    a("      STOP")
    a("      END")
    a("      SUBROUTINE PUTO(NAM, W)")
    a("      INTEGER W, T, D, DIGS(20), K")
    a("      CHARACTER*7 NAM")
    a("      T = W")
    a("      DO 10 K = 20, 1, -1")
    a("        D = T .AND. O\"7\"")
    a("        DIGS(K) = D")
    a("        T = SHIFT(T, -3)")
    a("   10 CONTINUE")
    a("      PRINT 20, NAM, DIGS")
    a("   20 FORMAT(' CDCVAL ',A7,1X,20I1)")
    a("      END")
    text = "\n".join(lines) + "\n"
    for lineno, line in enumerate(text.splitlines(), 1):
        if len(line) > 72:
            raise SystemExit(f"FAIL: fortran column {len(line)} > 72 at {lineno}: {line}")
        if line.startswith("C") or line.startswith(" "):
            continue
        raise SystemExit(f"FAIL: fortran column 1 at {lineno}: {line}")
    return text


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("cases")
    ap.add_argument("output", nargs="?", help="path, or stdout if omitted")
    args = ap.parse_args(argv)
    text = emit(parse_cases(args.cases))
    if args.output:
        with open(args.output, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
