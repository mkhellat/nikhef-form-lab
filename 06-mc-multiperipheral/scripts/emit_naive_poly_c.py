#!/usr/bin/env python3
"""Emit numeric/eval_naive_poly.h from the Section 3 naive sum (sympy).

Run from scripts/:  python3 emit_naive_poly_c.py
Regenerate when mumu_trace_lib.py changes.
"""
from pathlib import Path

from sympy.printing.c import C99CodePrinter

from mumu_trace_lib import compute_naive_Tij


def cname(sym):
    return str(sym).replace('.', '_')


class DotsPrinter(C99CodePrinter):
    def __init__(self, prefix='d->'):
        super().__init__()
        self._prefix = prefix

    def _print_Symbol(self, expr):
        return self._prefix + cname(expr)


def main():
    _, S = compute_naive_Tij(apply_onshell=True)
    n = len(S.as_ordered_terms()) if S.is_Add else (0 if S == 0 else 1)

    pd = DotsPrinter('d->')
    code_d = pd.doprint(S)
    # long double: same expr; caller compiles with a Dotsl* and we replace
    # pow( -> powl( and float literals — easier to emit two copies.
    pl = DotsPrinter('d->')
    code_l = pl.doprint(S).replace('pow(', 'powl(')

    fields = []
    for s in sorted(S.free_symbols, key=str):
        fields.append(cname(s))

    lines = []
    lines.append('/* Auto-generated by scripts/emit_naive_poly_c.py — do not edit. */')
    lines.append(f'/* Naive squared-amplitude polynomial, {n} monomials. */')
    lines.append('#ifndef EVAL_NAIVE_POLY_H')
    lines.append('#define EVAL_NAIVE_POLY_H')
    lines.append('#include <math.h>')
    lines.append('')
    lines.append('typedef struct {')
    for f in fields:
        lines.append(f'  double {f};')
    lines.append('} Dots;')
    lines.append('')
    lines.append('typedef struct {')
    for f in fields:
        lines.append(f'  long double {f};')
    lines.append('} Dotsl;')
    lines.append('')
    lines.append('static inline double eval_naive_poly(const Dots *d)')
    lines.append('{')
    lines.append(f'  return {code_d};')
    lines.append('}')
    lines.append('')
    lines.append('static inline long double eval_naive_poly_l(const Dotsl *d)')
    lines.append('{')
    lines.append(f'  return {code_l};')
    lines.append('}')
    lines.append('')
    lines.append('#endif')

    out = Path(__file__).resolve().parent.parent / 'numeric' / 'eval_naive_poly.h'
    out.write_text('\n'.join(lines) + '\n')
    print(f'wrote {out} ({n} monomials, {len(fields)} dots)')


if __name__ == '__main__':
    main()
