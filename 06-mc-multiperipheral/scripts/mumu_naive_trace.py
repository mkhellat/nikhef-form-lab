#!/usr/bin/env python3
"""
Naive ("standard fashion") squared amplitude for gamma*gamma* -> mu- mu+.

Computes the 16-term spin-summed trace
  S = Tr[(p6-slash + m) N (p7-slash - m) Nbar]
with N = N1+N2+N3+N4 as in report/mumu_cancellation.tex Section 3, reduces
each gamma chain by Clifford contraction (no gamma5 / Levi-Civita), and
collects a sum of scalar monomials in external dot products.

Writes:
  - human-readable summary to stdout
  - scripts/generated/mumu_naive_Tij.txt  (committed input for the appendix)

Depends on: mumu_trace_lib.py
Cross-check: mumu_gauge_check_squared.py must still vanish after any change here.
"""
from pathlib import Path

import sympy as sp

from mumu_trace_lib import compute_naive_Tij, monomial_count

HERE = Path(__file__).resolve().parent
OUT = HERE / 'generated' / 'mumu_naive_Tij.txt'


def main():
    results, S_total = compute_naive_Tij(apply_onshell=True)

    print('=' * 70)
    print('Naive squared-amplitude trace S = sum_{i,j} T_ij  (16 terms)')
    print('=' * 70)
    lines = []
    lines.append('# Generated by scripts/mumu_naive_trace.py - do not edit by hand.')
    lines.append('# Each T[Ni,Nj] includes its propagator denominator factor.')
    lines.append('# On-shell substitutions applied: p6.p6 = p7.p7 = m^2.')
    lines.append('# Momentum conservation among {e1,e2,k1,k2,p6,p7} is NOT imposed.')
    lines.append('# D1, D2 are kept as independent symbols (not substituted by k^2-m^2).')
    lines.append('')

    for (i, j), val in results.items():
        n = monomial_count(val)
        tag = '' if val != 0 else '   [vanishes]'
        print(f'T[{i},{j}] = {val}{tag}')
        lines.append(f'T[{i},{j}]  monomials={n}')
        lines.append(str(val))
        lines.append('')

    n_total = monomial_count(S_total)
    print()
    print('=' * 70)
    print('Sum of all 16 terms, fully expanded:')
    print('=' * 70)
    print(S_total)
    print()
    print(f'Number of distinct monomial terms in the fully expanded sum: {n_total}')

    lines.append(f'# S_total  monomials={n_total}')
    lines.append(str(S_total))
    lines.append('')

    # Denominator classification of the 98-term sum (falsifiable bookkeeping).
    d1 = sp.Symbol('D1')
    d2 = sp.Symbol('D2')
    collected = {d1**2: 0, d2**2: 0, d1 * d2: 0, 'other': 0}
    for term in sp.Add.make_args(S_total):
        # term = numer / denom_power; inspect free symbols in denominator via together
        t = sp.together(term)
        numer, denom = sp.fraction(t)
        densyms = denom.free_symbols
        if densyms == {d1}:
            collected[d1**2] += 1
        elif densyms == {d2}:
            collected[d2**2] += 1
        elif densyms == {d1, d2}:
            collected[d1 * d2] += 1
        else:
            collected['other'] += 1

    print()
    print('Monomials by denominator family:')
    print(f'  1/D1^2     : {collected[d1**2]}')
    print(f'  1/D2^2     : {collected[d2**2]}')
    print(f'  1/(D1 D2)  : {collected[d1 * d2]}')
    print(f'  other      : {collected["other"]}')
    lines.append('# monomials by denominator family')
    lines.append(f'# 1/D1^2    = {collected[d1**2]}')
    lines.append(f'# 1/D2^2    = {collected[d2**2]}')
    lines.append(f'# 1/(D1 D2) = {collected[d1 * d2]}')
    lines.append(f'# other     = {collected["other"]}')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n')
    print()
    print(f'Wrote {OUT.relative_to(HERE.parent)}')


if __name__ == '__main__':
    main()
